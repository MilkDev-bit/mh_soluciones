#!/bin/sh
# Exit on error, but with verbose logging
set -e

# Enable verbose logging to track execution
set -x

echo "🚀 Starting Frontend..."
echo "🔍 Environment Detection:"
echo "   - PORT: ${PORT:-8080}"
echo "   - VITE_API_URL_BASE: ${VITE_API_URL_BASE:-not set}"
echo "   - RAILWAY_ENVIRONMENT: ${RAILWAY_ENVIRONMENT:-not set}"
echo "   - RAILWAY_SERVICE_NAME: ${RAILWAY_SERVICE_NAME:-not set}"
echo "   - PWD: $(pwd)"
echo "   - USER: $(whoami)"

# Validate that required directories exist
if [ ! -d "/usr/share/nginx/html" ]; then
    echo "❌ ERROR: /usr/share/nginx/html directory does not exist!"
    exit 1
fi

if [ ! -d "/etc/nginx/conf.d" ]; then
    echo "❌ ERROR: /etc/nginx/conf.d directory does not exist!"
    exit 1
fi

# Check if nginx binary exists
if ! command -v nginx > /dev/null 2>&1; then
    echo "❌ ERROR: nginx command not found!"
    exit 1
fi

echo "✅ Pre-flight checks passed"

# Get PORT from environment or default to 8080 (matches Railway configuration)
PORT="${PORT:-8080}"

# Derive BACKEND_ORIGIN from VITE_API_URL_BASE for CORS headers
# VITE_API_URL_BASE format: https://backend-domain/api/v1
# We need to extract: backend-domain (without the /api/v1 part)
if [ -z "$VITE_API_URL_BASE" ]; then
    echo "❌ ERROR: VITE_API_URL_BASE environment variable is not set!"
    echo "   This variable should contain the backend API URL"
    echo "   Example: VITE_API_URL_BASE=https://backend.railway.app/api/v1"
    exit 1
fi

# Extract just the domain (remove https:// prefix and /api/v1 suffix)
# https://backend-production-21f4.up.railway.app/api/v1 -> backend-production-21f4.up.railway.app
BACKEND_ORIGIN=$(echo "$VITE_API_URL_BASE" | sed 's|^https\?://\([^/]*\).*|\1|')

if [ -z "$BACKEND_ORIGIN" ]; then
    echo "❌ ERROR: Could not derive BACKEND_ORIGIN from VITE_API_URL_BASE"
    exit 1
fi

echo "📍 Derived BACKEND_ORIGIN from VITE_API_URL_BASE: $BACKEND_ORIGIN"
echo "📍 Backend proxy will forward to Railway private network: http://backend.railway.internal:8080"

echo "📍 Configuring nginx to listen on port $PORT"
echo "📍 nginx will bind to 0.0.0.0:$PORT and [::]:$PORT"

# Generate nginx configuration
# This config file will be created at /etc/nginx/conf.d/default.conf
# It will replace any existing default.conf
cat > /etc/nginx/conf.d/default.conf << NGINX_EOF
# Nginx configuration for MH Soluciones Frontend
# Auto-generated by docker-entrypoint.sh
# Port: $PORT
# Backend Origin: $BACKEND_ORIGIN
# Proxy Target: http://backend.railway.internal:8080

# Upstream configuration would go here if we were using variables,
# but we're using hardcoded backend.railway.internal:8080 for Railway private networking

server {
    # Listen on all interfaces (IPv4 and IPv6)
    listen $PORT;
    listen [::]:$PORT;
    
    # Server name (Railway sets this via Host header)
    server_name _;

    client_max_body_size 900M;
    
    # Root directory where Vite build output is stored
    root /usr/share/nginx/html;
    
    # Default file to serve
    index index.html;
    
    # Logging
    access_log /var/log/nginx/access.log;
    error_log /var/log/nginx/error.log;
    
    # Security headers
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header X-XSS-Protection "1; mode=block" always;
    
    # Gzip compression
    gzip on;
    gzip_vary on;
    gzip_min_length 1024;
    # [RENDIMIENTO] Sin gzip_proxied, nginx NO comprime si la petición llega a
    # través de otro proxy (el de Railway): JS, CSS y JSON viajaban sin comprimir.
    gzip_proxied any;
    gzip_comp_level 5;
    gzip_types text/plain text/css text/xml text/javascript application/x-javascript application/rss+xml application/json application/javascript;
    
    # ===========================================================================
    # API PROXY - Routes /api/* to backend service via Railway private network
    # ===========================================================================
    # This allows the frontend to make API calls to relative URLs like:
    # fetch('/api/v1/auth/login/')
    # 
    # Frontend code uses relative URLs like '/api/v1/auth/login'
    # This prevents exposing the backend domain in client code
    location /api/ {
        proxy_pass http://backend.railway.internal:8080/api/;
        
        # Forward original request headers - preserve frontend Host for Django ALLOWED_HOSTS
        # Note: Headers are duplicated between /api/ and /media/ for clarity and independence
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header X-Forwarded-Host \$host;
        proxy_set_header X-Forwarded-Port \$server_port;
        
        # Timeouts
        proxy_connect_timeout 60s;
        proxy_send_timeout 60s;
        proxy_read_timeout 60s;
    }
    
    # ===========================================================================
    # WEBSOCKET PROXY - Routes /ws/* to backend service
    # ===========================================================================
    location /ws/ {
        proxy_pass http://backend.railway.internal:8080/ws/;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        
        # Forward original request headers
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        
        # Evitar que la conexión se cierre por inactividad (24 horas)
        proxy_read_timeout 86400s;
        proxy_send_timeout 86400s;
    }
    
    # ===========================================================================
    # MEDIA PROXY - Routes /media/* to backend service for user uploads
    # ===========================================================================
    # Django serves media files (user uploads, profile pictures, etc)
    # We proxy these requests to the backend
    # 
    # Proxies /media/* requests to the backend service
    # Allows serving user-uploaded files through the frontend domain
    location /media/ {
        proxy_pass http://backend.railway.internal:8080/media/;
        
        # Forward original request headers - preserve frontend Host for Django ALLOWED_HOSTS
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header X-Forwarded-Host \$host;
        proxy_set_header X-Forwarded-Port \$server_port;
        
        # Timeouts
        proxy_connect_timeout 60s;
        proxy_send_timeout 60s;
        proxy_read_timeout 60s;
        
        # ===================================================================
        # FORCE DOWNLOAD for Office documents and compressed files
        # ===================================================================
        # This ensures Word, Excel, PowerPoint, and compressed files are
        # downloaded instead of opening a blank page in the browser.
        # PDFs are not included here so they can still be viewed in-browser.
        # 
        # Supported formats:
        # - Word: .doc, .docx
        # - Excel: .xls, .xlsx
        # - PowerPoint: .ppt, .pptx
        # - Compressed: .zip, .rar, .7z
        # - Others: .txt (large files), .csv
        
        # Hide backend's Content-Disposition header to replace it
        proxy_hide_header Content-Disposition;
        
        # Set Content-Disposition based on file extension
        # Using map would be cleaner but requires separate block, so using if here
        # Note: This use of 'if' is safe because we're only setting a variable
        # (one of the documented safe uses of 'if' in nginx location blocks)
        set \$download_disposition "";
        
        if (\$request_uri ~* \.(docx?|xlsx?|pptx?|zip|rar|7z)\$) {
            set \$download_disposition "attachment";
        }
        
        # Apply the header if it was set
        add_header Content-Disposition \$download_disposition;
    }
    
    # ===========================================================================
    # STATIC ASSETS - Serve directly from nginx (optimal performance)
    # ===========================================================================
    # Vite bundles all static assets (JS, CSS, images, fonts) in /assets
    # We serve these directly from nginx for best performance
    location /assets/ {
        try_files \$uri =404;
        
        # Cache static assets aggressively (they have hash in filename)
        expires 1y;
        add_header Cache-Control "public, immutable";
    }
    
    # ===========================================================================
    # SPA ROUTING - All other requests serve index.html for React Router
    # ===========================================================================
    # React Router handles client-side routing
    # Any route that doesn't match /api/ or /media/ or /assets/ should serve index.html
    # This allows direct navigation to URLs like /dashboard, /documents, etc
    location / {
        try_files \$uri \$uri/ /index.html;
        
        # Don't cache the index.html file itself
        add_header Cache-Control "no-cache, no-store, must-revalidate";
        expires 0;
    }
    
    # ===========================================================================
    # FAVICON - Serve directly
    # ===========================================================================
    location = /favicon.ico {
        try_files \$uri =204;
        access_log off;
        log_not_found off;
    }
    
    # ===========================================================================
    # HEALTH CHECK - Simple ping endpoint for Railway
    # ===========================================================================
    location = /health {
        access_log off;
        return 200 "ok\n";
        add_header Content-Type text/plain;
    }
}
NGINX_EOF

echo "✅ Nginx configuration generated at /etc/nginx/conf.d/default.conf"
echo ""
echo "📄 Configuration summary:"
echo "   - Listening on port: $PORT"
echo "   - Backend origin (for logs): $BACKEND_ORIGIN"
echo "   - API proxy: /api/* -> http://backend.railway.internal:8080/api/*"
echo "   - WS proxy: /ws/* -> http://backend.railway.internal:8080/ws/*"
echo "   - Media proxy: /media/* -> http://backend.railway.internal:8080/media/*"
echo "   - Static files: /assets/* -> served from /usr/share/nginx/html/assets/*"
echo "   - SPA routing: /* -> /usr/share/nginx/html/index.html"
echo ""

# Validate nginx configuration
echo "🔍 Validating nginx configuration..."
if nginx -t; then
    echo "✅ Nginx configuration is valid"
else
    echo "❌ Nginx configuration validation failed!"
    echo "   Configuration file: /etc/nginx/conf.d/default.conf"
    cat /etc/nginx/conf.d/default.conf
    exit 1
fi

echo ""
echo "🚀 Starting nginx..."
echo "   - Nginx will run in foreground mode"
echo "   - Logs will be visible in Railway dashboard"
echo "   - Access logs: /var/log/nginx/access.log"
echo "   - Error logs: /var/log/nginx/error.log"
echo ""

# Start nginx in foreground mode (required for Docker)
# -g daemon off; keeps nginx running in foreground so the container doesn't exit
exec nginx -g 'daemon off;'